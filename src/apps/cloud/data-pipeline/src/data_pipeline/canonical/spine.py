"""canonical 등뼈 — **모든 테이블이 공유하는 축. 기계가 검사한다.**

보고서·재무·컨센서스·지분처럼 성격이 다른 자료가 계속 들어온다. 테이블마다 축을 따로
정하면 세 가지가 무너진다.

    조회   "이 종목 이 날" 을 묻는 질의가 테이블마다 다른 컬럼을 써야 한다
    결합   기간 표기가 갈려(bsns_year vs period vs fiscal_year) 조인이 안 된다
    PIT    "그 날 알 수 있었나" 를 판정하는 컬럼이 없거나 이름이 달라, 미래를 보는 것을
           막을 수 없다

그래서 **아홉 개 축을 필수로 못박고** 새 테이블이 그것을 갖췄는지 테스트가 검사한다.
문서로 적어 두면 지켜지지 않는다 - 검사할 수 있는 것은 검사로 옮긴다.

핵심은 **시간축이 둘**이라는 점이다.

    available_at   그 자료를 **언제 알 수 있었나** (발표일·접수일). PIT 의 근거
    period_key     그 자료가 **무엇에 대한 것인가** (2025-FY·2026-Q1·POINT)

둘을 하나로 뭉치면 조용히 미래를 본다. 2026-03-18 에 접수된 2025 사업보고서를 2025-12-31
자료로 쓰면 3개월을 앞서 아는 것이다. 이 구분이 없어서 무너지는 백테스트가 흔하다.
"""

from __future__ import annotations

# ── 대상 기간 어휘 ─────────────────────────────────────────────────────
# `period_key` 의 형식은 종류가 정한다. 파서를 두지 않고 형식을 고정하는 이유는, 문자열
# 비교만으로 정렬·범위 조회가 되게 하려는 것이다(2025-FY < 2026-FY).
PERIOD_TYPES = (
    "FY",     # 사업연도      2025-FY
    "HY",     # 반기          2025-H1
    "Q",      # 분기          2025-Q3
    "M",      # 월            2026-07
    "D",      # 일            2026-07-28
    "POINT",  # 시점 자료(스냅샷·사건). period_key 도 'POINT'
)

# reprt_code → (period_type, period_key 접미)
REPRT_PERIOD = {
    "11011": ("FY", "FY"),      # 사업보고서
    "11012": ("HY", "H1"),      # 반기보고서
    "11013": ("Q", "Q1"),       # 1분기
    "11014": ("Q", "Q3"),       # 3분기
}

# ── 필수 축 ────────────────────────────────────────────────────────────
# 이름과 타입까지 고정한다. 이름이 갈리면 조회가 테이블마다 달라지고, 타입이 갈리면
# (date vs string) 조인에서 조용히 캐스팅이 끼어든다.
SPINE: tuple[tuple[str, str, str], ...] = (
    ("entity", "string",
     "주 대상 티커. 산업·국가 문서는 빈 값 - NULL 이 아니라 빈 값이다(조인이 쉬워진다)"),
    ("geo", "string", "ISO 3166 또는 GLOBAL"),
    ("available_at", "date", "**언제 알 수 있었나.** 발표일·접수일. PIT 의 근거"),
    ("fetched_at", "timestamp", "우리가 처음 본 시각. 관측 창을 닫는 축"),
    ("period_key", "string", "**무엇에 대한 것인가.** 2025-FY·2026-Q1·POINT"),
    ("period_type", "string", "FY|HY|Q|M|D|POINT"),
    ("source", "string", "벤더·수집원"),
    ("src_run_id", "string", "어느 raw run 에서 왔나. 없으면 재현이 불가능하다"),
    ("src_ingest_date", "string", "raw 파티션의 수집일"),
)
SPINE_NAMES = tuple(n for n, _, _ in SPINE)

# 시간축을 파티션으로 쓸 때 허용하는 변환. 일 단위를 금지하는 이유는 하루 수십~수백 행짜리
# 파일이 수천 개 생겨 Athena 가 데이터보다 메타데이터를 더 읽기 때문이다.
TIME_PARTITIONS = ("month(available_at)", "year(available_at)")
